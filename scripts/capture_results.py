#!/usr/bin/env python3
"""Run every verification / measurement step for real and keep a screenshot of
its terminal (scripts/term_shot.py), then rebuild the documents that link them.

Each step is the normal command (make target or script); the screenshot shows
the prompt, the last screenful of its output and its exit status. Results in
results/ are regenerated by the same runs. The waveform screenshots
(GTKWave) are taken inside `make_waves.py` and `make cosim`.

Usage:
  capture_results.py                 # every step (about an hour, synth and cosim are long)
  capture_results.py --only unit,isa # a subset (names below)
"""
import argparse
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from term_shot import ROOT, Terminal  # noqa: E402

PY = ".venv/bin/python"
# name, command, screenshot (relative to ROOT), terminal rows
STEPS = [
    ("unit", "make unit", "results/unit/terminal_unit.png", 30),
    ("isa", "make isa", "results/isa/terminal_isa.png", 40),
    ("spike", "make spike", "results/spike/terminal_spike.png", 40),
    ("systest", "make systest", "results/systest/terminal_systest.png", 40),
    ("cov", "make cov", "results/coverage/terminal_cov.png", 75),
    ("synth", "JOBS=1 make synth", "results/synth/terminal_synth.png", 50),
    ("exp1", f"{PY} scripts/run_perf.py --exp 1", "results/perf/terminal_exp1.png", 30),
    ("exp2", f"{PY} scripts/run_perf.py --exp 2", "results/perf/terminal_exp2.png", 25),
    ("exp3", f"{PY} scripts/run_perf.py --exp 3", "results/perf/terminal_exp3.png", 30),
    ("exp4", f"{PY} scripts/run_perf.py --exp 4", "results/perf/terminal_exp4.png", 30),
    ("exp5", f"{PY} scripts/run_perf.py --exp 5", "results/perf/terminal_exp5.png", 30),
    ("throughput", f"{PY} scripts/throughput.py", "results/perf/terminal_throughput.png", 30),
    ("cosim", "make cosim", "results/cosim/terminal_cosim.png", 45),
    ("waves", f"{PY} scripts/make_waves.py", "results/waves/terminal_make_waves.png", 15),
    ("fpga", "make fpga", "results/fpga/terminal_make_fpga.png", 45),
    ("regress", "make regress", "results/terminal_regress.png", 50),
]


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only")
    args = ap.parse_args()
    names = args.only.split(",") if args.only else [s[0] for s in STEPS]
    bad = []
    with Terminal() as term:
        for name, cmd, out, rows in STEPS:
            if name not in names:
                continue
            t0 = time.time()
            print(f"[capture] {name:10s} {cmd}", flush=True)
            rc = term.run(cmd, ROOT / out, rows=rows)
            print(f"[capture] {name:10s} exit {rc}, {time.time() - t0:.0f} s -> {out}", flush=True)
            if rc != 0:
                bad.append(name)
    # summaries / documents that link the screenshots
    for script in ("run_perf.py --report-only", "make_results_md.py", "make_chapter4.py"):
        subprocess.run(f"{PY} scripts/{script}", shell=True, cwd=ROOT, check=False)
    if bad:
        sys.exit(f"[capture] steps with a non-zero exit status: {', '.join(bad)}")
    print("[capture] done")


if __name__ == "__main__":
    main()
